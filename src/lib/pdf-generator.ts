/**
 * Client-side PDF generation utility
 * Uses the browser's built-in print-to-PDF capability
 * via a hidden iframe approach, avoiding heavy server-side PDF libraries.
 */

/**
 * Generate a PDF from the application content using browser APIs
 * Creates a formatted HTML document and triggers print/save as PDF
 */
export function generatePDFContent(content: {
  coverLetter: string;
  cvKeywords: string;
  atsSuggestions: string;
  generatedCv: string;
}): void {
  const html = buildPDFHtml(content);

  const printWindow = window.open('', '_blank');
  if (!printWindow) {
    // Fallback: create a downloadable HTML file
    downloadAsHtml(html);
    return;
  }

  printWindow.document.write(html);
  printWindow.document.close();

  // Wait for content to load then trigger print
  printWindow.onload = () => {
    setTimeout(() => {
      printWindow.print();
    }, 500);
  };
}

