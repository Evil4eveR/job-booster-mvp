/**
 * Convert plain text to HTML with proper formatting
 */
function textToHtml(text: string): string {
  return text
    // Escape HTML entities
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    // Convert markdown-style bold
    .replace(/\*\*(.*?)\*\*/g, '<strong>$1</strong>')
    // Convert markdown-style headers (###)
    .replace(/^### (.+)$/gm, '<strong style="font-size: 12pt; color: #374151;">$1</strong>')
    .replace(/^## (.+)$/gm, '<strong style="font-size: 13pt; color: #059669;">$1</strong>')
    // Convert bullet points
    .replace(/^[-•] (.+)$/gm, '<span style="margin-left: 1em;">• $1</span>')
    .replace(/^\* (.+)$/gm, '<span style="margin-left: 1em;">• $1</span>');
}

/**
 * Download content as an HTML file (fallback)
 */
function downloadAsHtml(html: string): void {
  const blob = new Blob([html], { type: 'text/html' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = 'bewerbung-bundle.html';
  document.body.appendChild(a);
  a.click();
  URL.revokeObjectURL(url);
  document.body.removeChild(a);
}
